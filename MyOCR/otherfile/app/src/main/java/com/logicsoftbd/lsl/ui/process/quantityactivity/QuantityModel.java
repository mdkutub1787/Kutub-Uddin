package com.logicsoftbd.lsl.ui.process.quantityactivity;


public class QuantityModel {

    private int pos;
    private int qcQuantity;
    private int reject;
    private int alter;
    private int spot;
    private int replace;


    public int getPos() {
        return pos;
    }

    public void setPos(int pos) {
        this.pos = pos;
    }

    public int getQcQuantity() {
        return qcQuantity;
    }

    public void setQcQuantity(int qcQuantity) {
        this.qcQuantity = qcQuantity;
    }

    public int getReject() {
        return reject;
    }

    public void setReject(int reject) {
        this.reject = reject;
    }

    public int getAlter() {
        return alter;
    }

    public void setAlter(int alter) {
        this.alter = alter;
    }

    public int getSpot() {
        return spot;
    }

    public void setSpot(int spot) {
        this.spot = spot;
    }

    public int getReplace() {
        return replace;
    }

    public void setReplace(int replace) {
        this.replace = replace;
    }
}
